/** Run with node --import tsx. Canonical schemas -> JSON Schema + Python TypedDicts. */
import { z } from 'zod';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as contract from '../src/core/stateContract.ts';
import * as http from '../src/core/stateHttp.ts';
import { SubscribeResponseSchema } from '../src/store/stateBinding.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const specs = {};
for (const name of ['Scope', 'ExternalRef', 'DependencyRef', 'ActionReceipt', 'Commitment', 'DerivedState', 'Convention', 'WriteResult', 'CaptureBatchResult', 'RecordsResponse', 'ChangeEvent']) specs[name] = [contract[name + 'Schema'], 'output'];
for (const name of ['ReadRequest', 'WriteRequest', 'SubscribeRequest', 'RecordsRequest', 'CaptureRequest', 'CaptureBatchRequest']) specs[name] = [contract[name + 'Schema'].omit({ schema: true, principal: true }), 'input'];
Object.assign(specs, { ReadResponse: [http.HttpReadResponseSchema, 'output'], SubscribeResponse: [SubscribeResponseSchema, 'output'], CapabilitiesResponse: [http.HttpCapabilitiesSchema, 'output'], HealthResponse: [http.HttpHealthSchema, 'output'], StateProblem: [http.StateProblemSchema, 'output'] });
const schemas = Object.fromEntries(Object.entries(specs).map(([name, [schema, io]]) => [name, z.toJSONSchema(schema, { io, target: 'draft-2020-12' })]));
const definitions = [], memo = new Map();
const pascal = name => name.replace(/(^|[^A-Za-z0-9])([A-Za-z0-9])/g, (_, __, c) => c.toUpperCase());
const literal = value => value === true ? 'True' : value === false ? 'False' : value === null ? 'None' : JSON.stringify(value);
function typeOf(schema, name, top = false) {
  if (schema.$ref || schema.allOf) throw new Error('unsupported schema composition: ' + name);
  if ('const' in schema) return `Literal[${literal(schema.const)}]`;
  if (schema.enum) return `Literal[${schema.enum.map(literal).join(', ')}]`;
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return [...new Set(union.map((part, i) => typeOf(part, name + (i + 1))))].join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map(type => typeOf({ ...schema, type }, name)).join(' | ');
  if (schema.type === 'object' && schema.properties) {
    const signature = JSON.stringify(schema);
    if (!top && memo.has(signature)) return memo.get(signature);
    memo.set(signature, name);
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties).map(([key, value]) => {
      let field = typeOf(value, name + pascal(key));
      if (required.has(key)) field = `Required[${field}]`;
      return `    ${JSON.stringify(key)}: ${field},`;
    });
    definitions.push(`${name} = TypedDict(${JSON.stringify(name)}, {\n${fields.join('\n')}\n}, total=False)`);
    return name;
  }
  if (schema.type === 'object') return `dict[str, ${typeof schema.additionalProperties === 'object' ? typeOf(schema.additionalProperties, name + 'Value') : 'Any'}]`;
  if (schema.type === 'array') return `list[${typeOf(schema.items ?? {}, name + 'Item')}]`;
  const primitive = { string: 'str', integer: 'int', number: 'float', boolean: 'bool', null: 'None' }[schema.type];
  if (primitive) return primitive;
  if (!schema.type) return 'Any';
  throw new Error('unsupported schema type: ' + name);
}
for (const [name, schema] of Object.entries(schemas)) {
  const type = typeOf(schema, name, true);
  if (type !== name) definitions.push(`${name}: TypeAlias = ${type}`);
}
const model = '# Generated by tooling/generate-state-contracts.mjs; do not edit.\n# Types describe wire shapes; semantic validation remains server-owned.\nfrom typing import Any, Literal, Required, TypedDict, TypeAlias\n\n' + definitions.join('\n\n') + '\n';
const files = {
  'clients/python/src/hunch_state/models.py': model,
  'clients/python/src/hunch_state/schemas.json': JSON.stringify({ contract: contract.STATE_CONTRACT_VERSION, note: 'Generated structural schemas. Custom Zod refinements, authority, identity and dependency checks run on the server.', schemas }, null, 2) + '\n',
};
for (const [path, content] of Object.entries(files)) {
  const target = resolve(root, path);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== content) throw new Error('generated contract drift: ' + path);
  } else { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, content); }
}
console.log(`State contract ${process.argv.includes('--check') ? 'matches' : 'generated'}: ${Object.keys(schemas).length} schemas.`);
